BEGIN;
LOCK TABLE direct_messages IN SHARE ROW EXCLUSIVE MODE;
-- Identity values allocated by PostgreSQL are returned as strings, never JS floats.
-- The row lock on conversations serializes message insertion/commit per thread.
DO $$ BEGIN
  IF NOT EXISTS(SELECT 1 FROM information_schema.columns WHERE table_schema=current_schema() AND table_name='direct_messages' AND column_name='sequence') THEN
    ALTER TABLE direct_messages ADD COLUMN sequence bigint GENERATED BY DEFAULT AS IDENTITY;
    WITH ordered AS (SELECT id,row_number() OVER(ORDER BY created_at,id) AS n FROM direct_messages)
      UPDATE direct_messages m SET sequence=o.n FROM ordered o WHERE m.id=o.id;
    PERFORM setval(pg_get_serial_sequence('direct_messages','sequence'),greatest(coalesce((SELECT max(sequence) FROM direct_messages),0),1),EXISTS(SELECT 1 FROM direct_messages));
  END IF;
END $$;
ALTER TABLE direct_messages ADD COLUMN IF NOT EXISTS payload_hash text;
ALTER TABLE direct_messages ADD COLUMN IF NOT EXISTS reply_to_id uuid REFERENCES direct_messages(id) ON DELETE SET NULL;
ALTER TABLE direct_messages ADD COLUMN IF NOT EXISTS has_reply boolean NOT NULL DEFAULT false;
ALTER TABLE direct_messages ADD COLUMN IF NOT EXISTS gif jsonb;
ALTER TABLE direct_messages DROP CONSTRAINT IF EXISTS message_nonempty_limit;
-- Rerunning the earlier migration must not reject newer tombstone/media rows.
DO $$ BEGIN
  IF EXISTS(SELECT 1 FROM information_schema.columns WHERE table_schema=current_schema() AND table_name='direct_messages' AND column_name='photo_id') THEN
    ALTER TABLE direct_messages ADD CONSTRAINT message_nonempty_limit CHECK(length(trim(body))<=4000 AND
      (length(trim(body))>0 OR gif IS NOT NULL OR photo_id IS NOT NULL OR deleted_at IS NOT NULL OR media_expired_at IS NOT NULL));
  ELSE
    ALTER TABLE direct_messages ADD CONSTRAINT message_nonempty_limit CHECK(length(trim(body))<=4000 AND (length(trim(body))>0 OR gif IS NOT NULL));
  END IF;
END $$;
CREATE UNIQUE INDEX IF NOT EXISTS message_sequence_unique ON direct_messages(sequence);
CREATE INDEX IF NOT EXISTS message_thread_sequence ON direct_messages(thread_id,sequence);
COMMIT;
